"""Writes crates/brs-formats/src/bscr/signatures.rs: how many arguments each engine function
of the battle scripts takes and whether it returns a value, from the two tables in the
executable (0x171370 and 0x1720A8; each entry is {result kind, argument count, number}).
"""
import os, struct

import mips

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'crates', 'brs-formats', 'src', 'bscr', 'signatures.rs')
RETURNS = 0x81


def table(vaddr):
    entries = {}
    at = vaddr + mips.FILE_BIAS
    while True:
        kind, argc, number = struct.unpack_from('<3I', mips.DATA, at)
        if number == 0:
            break
        entries[number] = (argc, kind == RETURNS)
        at += 12
    assert sorted(entries) == list(range(1, len(entries) + 1)), 'numbers are not 1..n'
    return [entries[n] for n in range(1, len(entries) + 1)]


def emit(name, doc, entries):
    lines = [f'/// {doc}', f'pub const {name}: [Signature; {len(entries) + 1}] = [', '    NONE,']
    for i in range(0, len(entries), 6):
        row = ', '.join(f'sig({argc}, {str(returns).lower()})' for argc, returns in entries[i:i + 6])
        lines.append(f'    {row},')
    lines.append('];')
    return lines


lines = [
    '//! Generated by `tools_re/gen_natives.py` from the tables in the executable (0x171370 and',
    '//! 0x1720A8). Do not edit by hand.',
    '',
    '/// How a script calls an engine function: the arguments it pops and whether a result',
    '/// is pushed.',
    '#[derive(Clone, Copy, Debug, PartialEq, Eq)]',
    'pub struct Signature {',
    '    pub arguments: usize,',
    '    pub returns: bool,',
    '}',
    '',
    'const fn sig(arguments: usize, returns: bool) -> Signature {',
    '    Signature { arguments, returns }',
    '}',
    '',
    '/// Engine functions are numbered from 1.',
    'const NONE: Signature = sig(0, false);',
    '',
]
lines += emit('TABLE_1', 'The functions called with opcodes 0x82 and 0x86, by number.', table(0x171370))
lines.append('')
lines += emit('TABLE_2', 'The functions called with opcodes 0x87 and 0x88, by number.', table(0x1720a8))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
print(f'wrote {os.path.relpath(OUT)}')
